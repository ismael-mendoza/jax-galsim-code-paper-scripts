#!/usr/bin/env python3
"""Summarize the GPU profiles of full-scene drawing (the GPU-efficiency sentence of Sec 3.4).

Reads the traces written by `bin/profile_scene_gpu.py` (run by `sbatch/gpu-master.sbatch`):
one scene drawn `--n-repeats` times inside one `jax.profiler.trace`, with no compilation
or transfer inside the trace. Each draw is one profiler step ("draw_scene").

Sources, all measured (no FLOP or byte counts):
* xprof `overview_page`: time per step, split into device compute and "all others"
  (gaps on the GPU timeline between kernels; xprof does not say what causes them).
* xprof `kernel_stats`: one row per distinct kernel, with launch grid and block sizes,
  theoretical occupancy, number of launches and total duration. Memory copies are not
  kernels and are not in this table.
* the trace JSON (`*.trace.json.gz`): every GPU event (kernels and memory copies), used
  for kernel counts, the duration distribution and the time split by kind of kernel.

Kinds of kernel (by name): "FFT" (cuFFT kernels, name contains "fft"), "memcpy" (memory
copies), "XLA fusion" (kernels generated by XLA, name contains "fusion"; the largest are
transposes and concatenations), "cuBLAS" (`scal_kernel`, `gemm`, `cublas`), "other".

"Small kernels" are kernels launched with fewer thread blocks than the GPU has SMs
(`--n-sms`, 108 for the A100), so they cannot occupy every SM.

xprof's own `roofline_model` tool is not used: with xprof 2.24.2 it returns no per-op data
for traces from JAX 0.12.1 (its XLA does not know the `fma` opcode).

Usage (from the repository root; needs xprof, no GPU):
    uv run python bin/profile_summary.py
    uv run python bin/profile_summary.py --out output/profiles/summary.txt
"""

import gzip
import json
import math
from collections import Counter
from pathlib import Path

import numpy as np
import typer
from xprof.convert import raw_to_tool_data

# ---------------------------------------------------------------- parameters
PROFILES_DIR = Path(__file__).resolve().parents[1] / "output" / "profiles"
TRACE_GLOB = "jax-trace-scene-*-x*"  # one folder per profiled run
N_SMS = 108  # streaming multiprocessors on an NVIDIA A100
SHORT_US = 5.0  # kernels shorter than this (microseconds) are counted as "short"
TOP_N = 8  # kernels listed per run
# ----------------------------------------------------------------------------


def kind(name: str) -> str:
    n = name.lower()
    if "memcpy" in n:
        return "memcpy"
    if "fft" in n:
        return "FFT"
    if "fusion" in n:
        return "XLA fusion"
    if "scal_kernel" in n or "gemm" in n or "cublas" in n:
        return "cuBLAS"
    return "other"


def xprof_tool(xplane: Path, tool: str):
    data, _ = raw_to_tool_data.xspace_to_tool_data(
        [str(xplane)], tool, {"use_saved_result": False}
    )
    return json.loads(data.decode() if isinstance(data, bytes) else data)


def table_rows(table: dict) -> list[dict]:
    labels = [c["label"] for c in table["cols"]]
    return [dict(zip(labels, [c.get("v") for c in r["c"]])) for r in table["rows"]]


def n_blocks(dim: str) -> int:
    return math.prod(int(x) for x in str(dim).split(","))


def summarize(run_dir: Path, n_sms: int) -> list[str]:
    xplane = next(run_dir.glob("plugins/profile/*/*.xplane.pb"))
    trace = next(run_dir.glob("plugins/profile/*/*.trace.json.gz"))
    out = [f"== {run_dir.name}", f"   files: {xplane.parent}"]

    # ------------------------------------------------ overview page: per-step times
    ov = xprof_tool(xplane, "overview_page")
    steps = table_rows(ov[1])
    n_steps = len(steps)
    step_ms = np.array([s["Step time"] for s in steps])
    dev_ms = np.array([s["Device compute"] for s in steps])
    oth_ms = np.array([s["All others"] for s in steps])
    out += [
        f"   device: {ov[2]['p'].get('device_type', '?')}; steps (draws) in trace: {n_steps}",
        "   [overview_page] per draw, mean over steps:",
        f"      step time       {step_ms.mean():7.2f} ms",
        f"      device compute  {dev_ms.mean():7.2f} ms ({100 * dev_ms.mean() / step_ms.mean():.0f}%)",
        f"      all others      {oth_ms.mean():7.2f} ms ({100 * oth_ms.mean() / step_ms.mean():.0f}%)"
        "  <- gaps between kernels",
    ]

    # ------------------------------------------------ trace JSON: every GPU event
    ev = json.load(gzip.open(trace))["traceEvents"]
    pids = {
        e["pid"]: e["args"]["name"]
        for e in ev
        if e.get("ph") == "M" and e.get("name") == "process_name"
    }
    gpu_pid = next(p for p, n in pids.items() if "GPU" in n)
    gev = [e for e in ev if e.get("ph") == "X" and e["pid"] == gpu_pid]
    kev = [e for e in gev if kind(e["name"]) != "memcpy"]
    dur = np.array([e["dur"] for e in kev])  # microseconds
    gdur = np.array([e["dur"] for e in gev])
    by_kind = Counter()
    for e in gev:
        by_kind[kind(e["name"])] += e["dur"]
    # idle = gaps between consecutive GPU events, after merging overlapping events
    gsorted = sorted(gev, key=lambda e: e["ts"])
    starts = np.array([e["ts"] for e in gsorted])
    ends = starts + np.array([e["dur"] for e in gsorted])
    gaps = starts[1:] - np.maximum.accumulate(ends)[:-1]
    idle_ms = gaps[gaps > 0].sum() / 1e3
    span_ms = (ends.max() - starts.min()) / 1e3
    out += [
        "   [trace JSON] GPU events (all draws in the trace):",
        f"      kernels: {len(kev)} ({len(kev) / n_steps:.0f} per draw); "
        f"memory copies: {len(gev) - len(kev)} ({(len(gev) - len(kev)) / n_steps:.0f} per draw)",
        f"      kernel duration: median {np.median(dur):.1f} us, mean {dur.mean():.1f} us, "
        f"90th percentile {np.percentile(dur, 90):.1f} us; "
        f"{100 * (dur < SHORT_US).mean():.0f}% shorter than {SHORT_US:g} us",
        f"      GPU timeline: span {span_ms:.1f} ms, busy {gdur.sum() / 1e3:.1f} ms, "
        f"idle gaps {idle_ms:.1f} ms ({100 * idle_ms / span_ms:.0f}% of the span)",
        "      GPU busy time by kind (kernels + memory copies):",
    ]
    for k, v in by_kind.most_common():
        out.append(f"         {k:11s} {100 * v / gdur.sum():5.1f}%")

    # ------------------------------------------------ kernel stats: launch sizes
    ks_raw = xprof_tool(xplane, "kernel_stats")  # one table (dict), not a list
    ks = table_rows(ks_raw[0] if isinstance(ks_raw, list) else ks_raw)
    T = next(c for c in ks[0] if c.startswith("Total Duration"))
    tot = sum(r[T] for r in ks)
    n_launch = sum(r["Occurrences"] for r in ks)
    small = [r for r in ks if n_blocks(r["Grid dim"]) < n_sms]
    occ = sum(r["Theoretical Occupancy %"] * r[T] for r in ks) / tot
    out += [
        f"   [kernel_stats] {len(ks)} distinct kernels, {n_launch:.0f} launches, "
        f"{tot / 1e3:.1f} ms total (memory copies not included):",
        f"      small kernels (fewer than {n_sms} thread blocks = SMs): "
        f"{100 * sum(r['Occurrences'] for r in small) / n_launch:.0f}% of launches, "
        f"{100 * sum(r[T] for r in small) / tot:.0f}% of kernel time",
        f"      theoretical occupancy, weighted by kernel time: {occ:.0f}%",
        f"      top {TOP_N} kernels by total time:",
        "         time%  launches  blocks(grid)   threads/block  occupancy  name",
    ]
    for r in sorted(ks, key=lambda r: -r[T])[:TOP_N]:
        out.append(
            f"         {100 * r[T] / tot:5.1f}  {r['Occurrences']:8.0f}  "
            f"{n_blocks(r['Grid dim']):12d}  {n_blocks(r['Block dim']):13d}  "
            f"{r['Theoretical Occupancy %']:8.0f}%  {r['Kernel Name'][:60]}"
        )
    return out


def main(
    profiles_dir: Path = typer.Option(PROFILES_DIR, help="Folder with the traces."),
    n_sms: int = typer.Option(N_SMS, help="SMs of the profiled GPU (A100: 108)."),
    out: Path = typer.Option(None, help="Optional text file for the summary."),
):
    runs = sorted(profiles_dir.glob(TRACE_GLOB))
    assert runs, f"no traces matching {TRACE_GLOB} in {profiles_dir}"
    lines = []
    for run_dir in runs:
        lines += summarize(run_dir, n_sms) + [""]
    text = "\n".join(lines)
    print(text)
    if out is not None:
        out.write_text(text)
        print(f"Saved {out}")


if __name__ == "__main__":
    typer.run(main)
